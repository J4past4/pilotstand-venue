let idCounter = 1;
export function createItemId(prefix = 'item'): string {
  idCounter += 1;
  return `${prefix}-${Date.now().toString(36)}-${idCounter}`;
}

export function instantiateTemplate(template: StandTemplate): {
  config: StandConfig;
  items: StandItem[];
} {
  const config: StandConfig = {
    ...DEFAULT_STAND_CONFIG,
    ...template.config,
    shellArtwork: { ...(template.config.shellArtwork || {}) },
  };
  const items: StandItem[] = template.items.map((item, idx) => ({
    ...item,
    id: createItemId(`tpl-${idx}`),
    dims: { ...item.dims },
    artwork: Object.fromEntries(
      Object.entries(item.artwork || {}).map(([k, v]) => [k, { ...v }])
    ),
    locked: false,
    visible: true,
  }));
  return { config, items };
}
